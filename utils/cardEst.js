// P0-3 估算卡判定（单源）
// ───────────────────────────────────────────────────────────────────────────
// 「系统估的行」= 选品类时由品类默认模板预填的行（isPreset === true）。
// 只要任一明细行仍是系统估的，整张卡就处于「估算卡」状态：
//   ① 编辑器给这些行黄底 + 「系统先估的·可改」角标；
//   ② 卡片级横幅提示「存的是估算卡，核对后再当正式卡用」；
//   ③ fail-closed：估算卡的成本本身含占位（价格可能空）⇒ 不触发「售价低于成本」假预警
//      （成本不可信时比了也没意义，横幅已告知用户这是估算）。
// 用户改了任意预填行 ⇒ 该行 isPreset 置 false（见 edit.js 输入处理器）⇒
//   全部预填行都被用户接管后，整卡自动退出「估算卡」状态。
// ---------------------------------------------------------------------------
function isEstimatedCard(lines) {
  if (!Array.isArray(lines)) return false;
  return lines.some((l) => !!(l && l.isPreset === true));
}

module.exports = { isEstimatedCard };
