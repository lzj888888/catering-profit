// utils/lineKind.js —— 按原料名推断「组件类型」（line_kind）
//
// 🔴 R678（李老师：「每行都要选主料/辅料/调料，填起来容易疲劳」）
//
// 这个字段该不该留？**该留** —— 它在多规格试算里是系数维度：
//   `coef: { main, aux, season, semi, pack }`
//   老板做「小份版」时，主料减半、**调料不能减半**（火候油盐差不多）。
//   若所有行一起乘 0.5，成本就错了。所以字段本身有真价值。
//
// **但不该让老板每行手点一次** —— 那是不必要的心智负担。
// 而且原来套用模板时，糖/醋/酱油/油**全被标成「主料」**，
// 做半份试算时调料跟着减半 ⇒ 成本算错，界面还看不出来。
//
// ⇒ 改成：**自动推断 + 老板想改才点**。
//   推断原则：**只在没设过的时候推**（`undefined` / 空）；
//   老板明确选过（包括明确选了「主料」）就**不许改** —— R626 教训：「我明明填了却变了」。

// 与云函数侧 LINE_KINDS 同源（各云函数目录下的 cx_specDerive.js）
// 🔴 原写法是 `cloudfunctions` + 斜杠 + 星号 + 斜杠 —— 行注释里出现「星号斜杠」会让
//   前面的块注释提前结束、**吞掉后面整段代码**。check_comment_safety 当场抓到。
const LINE_KINDS = ['main', 'aux', 'season', 'semi', 'pack'];

// 明确的液体 / 粉末 / 酱料类调料 —— 这些在任何菜里都是「调味」性质
// ⚠️ 注意「青椒」不能命中（它是配菜不是调料）⇒ 规则用「辣椒」而不是「椒」
const SEASON_RE = /油|盐|糖|醋|酱油|生抽|老抽|豉油|酱|料酒|黄酒|淀粉|生粉|味精|鸡精|鸡粉|蚝油|豆瓣|豆豉|花椒|辣椒|胡椒|香料|八角|桂皮|香叶|丁香|小茴香|孜然|咖喱|五香|醪糟|酵母|膨松|碱|苏打|嫩肉粉|硼砂|色素|香精/;

// 香辛蔬菜 / 腌菜类 —— 起调味作用但是实体食材，归「辅料」
// ⚠️ 首版漏了「青椒」—— 它不含「辣椒」二字，但也不是调料（是配菜）。
//   规则要的是「哪些是配菜」，不是「含椒字就是调料」。
const AUX_RE = /葱|姜|蒜|香菜|芹菜|青椒|尖椒|彩椒|杭椒|泡椒|榨菜|芽菜|冬菜|梅干菜|酸豆角|胡萝卜|木耳|青笋|莴笋/;

// 半成品（中央厨房/外购预制）
const SEMI_RE = /半成品|预制|成品料|料包|底料|丸子|虾滑|酥肉|酱料包/;

// 包装物（餐盒/袋/杯）
const PACK_RE = /餐盒|打包|包装|一次性|纸杯|塑料|袋子|吸管|餐巾/;

/**
 * 按原料名推断组件类型。
 * @param {string} name 原料名
 * @returns {'main'|'aux'|'season'|'semi'|'pack'} 推断不出时返回 'main'
 *
 * ⚠️ 顺序即优先级：包装 > 半成品 > 调料 > 香辛蔬菜 > 主料
 *   （「成品牛油底料」既是半成品又含「油」「底料」，必须半成品优先，
 *     否则会被当成调料 —— 它是这道菜的主体成本）
 */
// 「食材主体词」—— 带这些词说明这道料本身是食材，不是调味品。
// 🔴 这条是必须的：「油酥花生米」含「油」但主体是花生米（主料）；
//   只看「含油字」会把 50g 花生米判成调料，做小份试算时它就不减半 ⇒ 成本算高。
// ⚠️ 用完整词（鸡肉/鸡腿/鸡蛋）而不是单字（鸡），否则「鸡精」会被当成鸡肉。
const FOOD_CORE_RE = /花生|米饭|大米|面粉|面条|粉丝|豆腐|鸡肉|鸡腿|鸡胸|鸡翅|鸡爪|鸡蛋|猪肉|牛肉|羊肉|鱼|虾|肉末|肉馅|排骨|青菜|白菜|土豆|茄子|番茄|萝卜|藕|笋|菌|菇|木耳/;

function stripParen(v) {
  return String(v == null ? '' : v).replace(/（[^）]*）/g, '').replace(/\([^)]*\)/g, '').trim();
}

function inferLineKind(name) {
  const s = stripParen(name);
  if (!s) return 'main';                  // 还没填名字 ⇒ 先当主料（不改动用户输入）
  if (PACK_RE.test(s)) return 'pack';
  if (SEMI_RE.test(s)) return 'semi';
  // 「油」只在**结尾**才算调料（食用油 / 辣椒油 / 牛油）；
  // 出现在开头是「做法」（油酥花生米 / 油炸酥肉）⇒ 不是调料。
  // 🔴 调味**后缀**优先于「食材核心」：判断一个词是不是调料，看它最后落在什么品类上。
  //   「番茄酱」含「番茄」但它是酱 ⇒ 调料；「番茄」本身 ⇒ 主料。
  //   「花生米」结尾是「米」⇒ 不会被这条抓走（它确实是主料）。
  //   ⚠️ 后缀只放明确的调味形态（酱/汁/膏/油/醋），**不放「粉」** ——
  //      面粉、米粉、土豆粉都是主料，放进去会把主食判成调料。
  if (/(酱|汁|膏|油|醋)$/.test(s)) return 'season';
  const isFoodCore = FOOD_CORE_RE.test(s);
  if (SEASON_RE.test(s) && !isFoodCore) return 'season';
  if (AUX_RE.test(s)) return 'aux';
  return 'main';
}

/**
 * 是否「没设过」—— 只有这种情况才允许自动推断覆盖。
 * `undefined` / `null` / `''` 算没设过；明确的 `'main'` 算**老板选过了**（不覆盖）。
 */
function isUnset(kind) {
  return kind === undefined || kind === null || kind === '';
}

module.exports = { inferLineKind, isUnset, LINE_KINDS };
