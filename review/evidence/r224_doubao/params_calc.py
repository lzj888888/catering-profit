"""R224：两份 BP 成本占比机器化 —— 用于判定「火锅水电燃气占比」口径"""
def pct(a, b): return a / b * 100.0

print('=' * 78)
print('案例1 卤鸡火锅（小鸡快跑）100㎡ · 月营收 14.5 万，月固定 5.66 万')
rev = 145000
items = [('房租', 12000), ('人工', 25000), ('水电燃气(三情景表)', 7500),
         ('水电燃气(租金梯度120档)', 6500), ('其他杂费', 6000), ('折旧', 6100)]
for n, v in items:
    print('   %-26s %7d 元   占营收 %5.2f%%' % (n, v, pct(v, rev)))
print('   房租占比红线（文档自述）≤15%%   实算 %.2f%%' % pct(12000, rev))
print('   人工占比区间（文档自述）10–20%% 实算 %.2f%%' % pct(25000, rev))
print('   管理费（按营收 3%%）        %7d 元   占营收 %5.2f%%' % (4350, pct(4350, rev)))
print()
print('=' * 78)
print('案例2 火锅浇头小面 50㎡ · 保本营收 43,269，基准营收 9 万 / 11 万')
fixed = [('房租', 3000), ('人工', 13500), ('水电燃气', 3600), ('员工餐', 1800), ('网费+垃圾', 600)]
for n, v in fixed:
    print('   %-26s %7d 元   占保本营收 %5.2f%%   占9万营收 %5.2f%%   占11万营收 %5.2f%%'
          % (n, v, pct(v, 43269), pct(v, 90000), pct(v, 110000)))
tot = sum(v for _, v in fixed)
print('   月固定合计 %d 元（文档写 22500）' % tot)
print('   水电燃气公式 = 2600 + 面积×20 ⇒ 45㎡=%d  50㎡=%d  60㎡=%d'
      % (2600 + 20 * 45, 2600 + 20 * 50, 2600 + 20 * 60))
print()
print('=' * 78)
print('🔴 判定：火锅业态「水电燃气占营收比」')
r1 = [pct(6500, rev), pct(7500, rev)]
r2 = [pct(3600, 43269), pct(3600, 90000), pct(3600, 110000)]
print('   卤鸡火锅 100㎡: %.2f%% ~ %.2f%%' % (min(r1), max(r1)))
print('   火锅小面 50㎡ : %.2f%% ~ %.2f%%' % (min(r2), max(r2)))
print('   仓内 [D1] 火锅水电口径 = 4~6%%')
print('   豆包早前给的区间       = 8~12%%')
print('   ⇒ 两份独立 BP 实测均落在 %s ⇒ 与仓内 [D1]（4~6%%）一致，与豆包 8~12%% 不符'
      % ('4~6% 区间内' if max(r1) <= 6.5 and max(r2) <= 6.5 else '待复核'))
