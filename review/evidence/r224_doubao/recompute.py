"""R224 两案例回本口径反推：检验回本 = 投资/(净利+折旧) 还是 投资/净利"""
def line(tag, s): print('  %-34s %s' % (tag, s))

print('===== 案例1 小鸡快跑·卤鸡半自助火锅（含折旧在固定成本内）=====')
inv = {80: 21.2, 100: 26.2, 120: 31.1}          # 万元
profit = {80: 0.8, 100: 1.6, 120: 1.4}         # 月净利 万元
dep_doc = {100: 0.61}                          # 文档明写 100㎡ 折旧 0.61万/月
pay_doc = {80: 15.9, 100: 11.8, 120: 14.6}     # 文档自报回本月数
line('面积', '投资(万) 月净利(万) 文档回本(月) 投资/净利  反推折旧(万/月)')
for a in (80, 100, 120):
    d_implied = inv[a] / pay_doc[a] - profit[a]
    line('%d㎡' % a, '%6.1f %8.2f %10.1f %10.2f %12.3f' % (inv[a], profit[a], pay_doc[a], inv[a]/profit[a], d_implied))
line('100㎡ 正算校验', '26.2/(1.6+0.61) = %.2f 月  vs 文档 11.8/11.9 月' % (inv[100]/(profit[100]+dep_doc[100])))
print()
print('===== 案例2 火锅浇头小面（固定成本结构里没有折旧科目）=====')
inv2 = 24.0    # 万元
line('月营收11万 净利', '3.47 万')
line('投资/净利', '%.2f 月  vs 文档 6.9 月  ⇒ 口径 = 投资/净利（不含折旧）' % (inv2/3.47))
line('月固定', '2.25 万 = 租金0.3+人工1.35+水电0.36+员工餐0.18+网费垃圾0.06（无折旧）')
print()
print('===== 结论 =====')
print('  🔴 两份 BP 的“回本周期”口径不一致：')
print('     卤鸡火锅 = 投资 ÷ (月净利 + 月折旧)   ← 现金流口径（投资≠全部进成本）')
print('     火锅面   = 投资 ÷ 月净利              ← 简单口径（无折旧科目）')
print('  ⇒ 同一指标两口径，本仓若只实现一种，另一个业态必然算错。')
print('  ⇒ 100㎡ 两口径差：11.8 月 vs 16.4 月（差 39%）')
