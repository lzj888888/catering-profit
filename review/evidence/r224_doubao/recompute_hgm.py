"""R224 自纠取证：复核火锅面 8.2 多情景表是否自洽。

背景：我最初据"紧凑小店行 投资 15 万、回本 4.3 月"推断该表不自洽 —— 结果是我用错了净利数
（拿基准店的 34,700 套到紧凑小店行）。本脚本逐行用"投资 ÷ 本月净利@11万"复算，证明该表自洽。
教训：本仓纪律「报红先怀疑自己」在人工读表时同样适用。
"""
rows = [
    ('基准店',     22500,  80, 34700, 24.0, 6.9),
    ('2 人精简',   17400,  62, 39800, 20.0, 5.0),
    ('紧凑小店',   21590,  77, 35610, 15.0, 4.3),
    ('保守高租',   25220,  90, 31980, 30.0, 9.4),
    ('大店重装饰', 30840, 110, 26360, 33.0, 12.5),
]
print('%-10s %8s %8s %10s %9s %9s %8s %8s' %
      ('场景', '月固定', '日锅', '净利@11万', '投资(万)', '投资/净利', '文档回本', '偏差%'))
worst = 0.0
for n, fix, pot, prof, inv, doc in rows:
    calc = inv * 10000 / prof
    dev = (calc - doc) / doc * 100
    worst = max(worst, abs(dev))
    print('%-10s %8d %8d %10d %9.1f %9.2f %8.1f %+8.2f' % (n, fix, pot, prof, inv, calc, doc, dev))
print()
print('最大偏差 = %.2f%%  ⇒ %s' % (worst, '内部自洽' if worst < 3 else '存在矛盾'))
print('同时印证：该表回本口径 = 投资 ÷ 月净利（**不**加回折旧），与卤鸡火锅那份（加回折旧）不同。')
